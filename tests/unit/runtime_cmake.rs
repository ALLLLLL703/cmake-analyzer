// AI-generated process failure, output-bound, and cancellation tests.
#[cfg(unix)]
mod unix {
    use cmake_analyzer::runtime_cmake::{
        configure,
        model::{ConfigureOptions, RunId},
    };
    use lspally::server::model::Cancellation;
    use std::{
        sync::atomic::{AtomicU64, Ordering},
        time::Duration,
    };
    static NEXT: AtomicU64 = AtomicU64::new(0);
    async fn options(script: &str) -> ConfigureOptions {
        use std::os::unix::fs::PermissionsExt;
        let root = std::env::temp_dir().join(format!(
            "cmake-process-test-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        tokio::fs::create_dir_all(&root).await.unwrap();
        let executable = root.join("cmake");
        let path = executable.clone();
        let contents =
            format!("#!/bin/sh\n# Script-generated by tests/unit/runtime_cmake.rs.\n{script}\n");
        // Close executable writers before exec, including with Tokio's io-uring backend.
        tokio::task::spawn_blocking(move || {
            std::fs::write(&path, contents).unwrap();
            std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o700)).unwrap();
        })
        .await
        .unwrap();
        ConfigureOptions {
            mode: cmake_analyzer::runtime_cmake::model::ExecutionMode::Configure,
            executable,
            source_directory: root.clone(),
            build_directory: root.join("build"),
            arguments: vec![],
            timeout: Duration::from_secs(5),
            max_output_bytes: 4096,
            max_error_bytes: 128,
        }
    }
    #[tokio::test]
    async fn failures_surface_non_trace_details_and_invalid_trace_is_not_published() {
        for (script, expected) in [
            (
                "printf 'fatal fixture error\\n' >&2; exit 1",
                "fatal fixture error",
            ),
            ("printf 'not a trace\\n' >&2", "no JSON trace"),
        ] {
            let options = options(script).await;
            let root = options.source_directory.clone();
            let error = configure(RunId::new(1), options, Cancellation::default())
                .await
                .unwrap_err();
            assert!(error.to_string().contains(expected), "{error}");
            tokio::fs::remove_dir_all(root).await.unwrap();
        }
    }
    #[tokio::test]
    async fn output_limits_timeouts_and_precancel_do_not_leave_running_children() {
        let mut bounded = options("printf '01234567890123456789' >&2; exec sleep 60").await;
        bounded.max_output_bytes = 8;
        bounded.mode = cmake_analyzer::runtime_cmake::model::ExecutionMode::Script {
            file: bounded.source_directory.join("input.cmake"),
        };
        let root = bounded.source_directory.clone();
        assert!(
            configure(RunId::new(1), bounded, Cancellation::default())
                .await
                .unwrap_err()
                .to_string()
                .contains("limit")
        );
        tokio::fs::remove_dir_all(root).await.unwrap();
        let mut timed = options("exec sleep 60").await;
        timed.timeout = Duration::from_millis(100);
        timed.mode = cmake_analyzer::runtime_cmake::model::ExecutionMode::Script {
            file: timed.source_directory.join("input.cmake"),
        };
        let root = timed.source_directory.clone();
        assert_eq!(
            configure(RunId::new(2), timed, Cancellation::default())
                .await
                .unwrap_err()
                .kind(),
            std::io::ErrorKind::TimedOut
        );
        tokio::fs::remove_dir_all(root).await.unwrap();
        let cancelled = options("touch marker").await;
        let root = cancelled.source_directory.clone();
        let cancel = Cancellation::default();
        cancel.cancel();
        assert_eq!(
            configure(RunId::new(3), cancelled, cancel)
                .await
                .unwrap_err()
                .kind(),
            std::io::ErrorKind::Interrupted
        );
        assert!(!root.join("marker").exists());
        tokio::fs::remove_dir_all(root).await.unwrap();
    }
}
