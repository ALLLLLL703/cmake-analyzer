// AI-generated end-to-end real CMake trace/layer tests; projects use no compiler languages.

//! Check runtime-layer installation against a real CMake configure of trusted test-authored text.
//! Creates a compiler-free temporary project and build tree, runs CMake, and removes the tree on drop.
//! Documentation examples are local-context text, not additional configure invocations.

use super::Project;
use cmake_analyzer::{
    config::Runtime,
    runtime_cmake::{
        configure,
        model::{ConfigureOptions, RunId},
    },
    workspace::runtime::ValueNamespace,
};
use lspally::server::model::Cancellation;
use std::{sync::Arc, time::Duration};
/// Configure the trusted compiler-free Trace fixture with CACHEV=custom and install its captured runtime trace.
/// Writes temporary sources and a dedicated-build tree, spawns/reaps real CMake, loads trace sources, and removes the project tree on drop. Not used as an executable documentation example.
///
/// # Arguments
/// None; the test constructs its own fixtures.
///
/// # Returns
/// `()` after all checks pass.
///
/// # Panics
/// If fixture setup or any documented assertion fails.
///
/// # Algorithm
/// Compare static and observed dependencies, including empty files; require functions/repeated calls, normal/cache/unknown value distinctions, immutable static snapshot identity, atomic cancellation, and runtime invalidation on overlay edit.
///
/// # Flow
/// ```text
/// [trusted Trace fixture] --> [static snapshot / graph]
///           |                         |
///           v                         v
/// [CMake configure / trace] --> [install runtime layer]
///                                     |
///                                     v
///                        [dependencies / calls / values]
///                                     |
///                                     v
/// [pre-cancelled new trace] --> [old layer retained]
///                                     |
///                                     v
/// [root overlay edit] --------> [runtime layer cleared]
/// ```
///
/// # Examples
/// Local test-module context, outside any running Tokio runtime:
/// the macro-generated test wrapper runs its own runtime and returns `()`.
/// Prefer the test harness; ignored measurements require explicit selection.
/// ```text
/// observed_dependencies_values_functions_and_repeated_calls_stay_separate();
/// ```
#[tokio::test]
async fn observed_dependencies_values_functions_and_repeated_calls_stay_separate() {
    let p = Project::new().await;
    p.write("CMakeLists.txt","project(Trace NONE)\nfunction(makepath output)\nset(${output} \"${CMAKE_CURRENT_SOURCE_DIR}/runtime\" PARENT_SCOPE)\nendfunction()\nmakepath(DYNAMIC)\ninclude(\"${DYNAMIC}/new.cmake\")\ninclude(\"${DYNAMIC}/empty.cmake\")\nadd_subdirectory(\"${DYNAMIC}/sub\")\nruntime_fn()\nruntime_fn()\nruntime_macro()\nmessage(\"${VALUE}\")\nset(CACHEV default CACHE STRING doc)\nmessage(\"${CACHEV}\")\nset(OPTIONS \"x;CACHE;STRING;doc;FORCE\")\nset(UNSAFE ${OPTIONS})\nmessage(\"${UNSAFE}\")\n").await;
    p.write("runtime/new.cmake","set(VALUE module)\nfunction(runtime_fn)\nmessage(\"${VALUE}\")\nendfunction()\nmacro(runtime_macro)\nmessage(\"${VALUE}\")\nendmacro()\n").await;
    p.write(
        "runtime/sub/CMakeLists.txt",
        "function(child_fn)\nendfunction()\nadd_subdirectory(empty)\n",
    )
    .await;
    tokio::fs::write(
        p.0.join("runtime/empty.cmake"),
        "# Script-generated by tests/unit/workspace/runtime.rs.\n",
    )
    .await
    .unwrap();
    tokio::fs::create_dir_all(p.0.join("runtime/sub/empty"))
        .await
        .unwrap();
    tokio::fs::write(
        p.0.join("runtime/sub/empty/CMakeLists.txt"),
        "# Script-generated by tests/unit/workspace/runtime.rs.\n",
    )
    .await
    .unwrap();
    let mut workspace = p.workspace();
    workspace.flush().await.unwrap();
    let before = workspace
        .snapshot(p.0.join("CMakeLists.txt"))
        .unwrap()
        .unwrap();
    assert!(
        !workspace
            .root_graph()
            .unwrap()
            .invocations
            .iter()
            .any(|visit| visit.file.ends_with("new.cmake"))
    );
    let defaults = Runtime::default();
    let trace = configure(
        RunId::new(1),
        ConfigureOptions {
            mode: cmake_analyzer::runtime_cmake::model::ExecutionMode::Configure,
            executable: defaults.executable,
            source_directory: p.0.clone(),
            build_directory: p.0.join("dedicated-build"),
            arguments: vec!["-DCACHEV=custom".into()],
            timeout: Duration::from_secs(defaults.timeout_seconds),
            max_output_bytes: defaults.max_output_bytes,
            max_error_bytes: defaults.max_view_bytes,
        },
        Cancellation::default(),
    )
    .await
    .unwrap();
    assert!(trace.dependencies.iter().any(|dependency| {
        dependency
            .resolved
            .as_ref()
            .is_some_and(|path| path.ends_with("runtime/new.cmake"))
    }));
    assert!(trace.dependencies.iter().any(|dependency| {
        dependency
            .resolved
            .as_ref()
            .is_some_and(|path| path.ends_with("runtime/sub/CMakeLists.txt"))
    }));
    for suffix in ["runtime/empty.cmake", "runtime/sub/empty/CMakeLists.txt"] {
        assert!(
            trace.dependencies.iter().any(|dependency| dependency
                .resolved
                .as_ref()
                .is_some_and(|path| path.ends_with(suffix))),
            "{suffix}"
        );
    }
    workspace.install_runtime(trace).await.unwrap();
    let layer = workspace.runtime().unwrap();
    assert!(layer.documents.contains_key(&p.0.join("runtime/new.cmake")));
    for name in ["runtime_fn", "runtime_macro", "child_fn"] {
        assert!(
            layer.functions.iter().any(|function| function.name == name),
            "{name}"
        );
    }
    assert_eq!(
        layer
            .functions
            .iter()
            .find(|function| function.name == "runtime_fn")
            .unwrap()
            .calls
            .len(),
        2
    );
    assert!(layer.values.iter().any(|value| {
        value.name == "VALUE"
            && value
                .possible_value
                .as_ref()
                .is_some_and(|value| value.text() == "module")
    }));
    assert!(layer.values.iter().any(|value| value.name == "CACHEV"
        && value.namespace == ValueNamespace::Cache
        && value.possible_value.is_none()));
    assert!(layer.values.iter().any(|value| {
        value.name == "CACHEV"
            && value
                .possible_value
                .as_ref()
                .is_some_and(|value| value.text() == "custom")
    }));
    assert!(layer.values.iter().any(|value| value.name == "UNSAFE"
        && value.namespace == ValueNamespace::Unknown
        && value.possible_value.is_none()));
    assert!(layer.values.iter().any(|value| {
        value.name == "UNSAFE"
            && value
                .possible_value
                .as_ref()
                .is_some_and(|value| value.text() == "x")
    }));
    assert!(Arc::ptr_eq(
        &before,
        &workspace
            .snapshot(p.0.join("CMakeLists.txt"))
            .unwrap()
            .unwrap()
    ));
    assert!(workspace.root_graph().unwrap().runtime.is_some());
    let previous = workspace.runtime().unwrap().clone();
    let cancelled = Cancellation::default();
    cancelled.cancel();
    let empty = cmake_analyzer::runtime_cmake::model::Trace {
        run: RunId::new(2),
        build_directory: Some(p.0.join("dedicated-build")),
        events: Vec::new(),
        dependencies: Vec::new(),
    };
    assert_eq!(
        workspace
            .install_runtime_cancellable(empty, cancelled)
            .await
            .unwrap_err()
            .kind(),
        std::io::ErrorKind::Interrupted
    );
    assert!(Arc::ptr_eq(&previous, workspace.runtime().unwrap()));
    workspace
        .set_overlay(
            p.0.join("CMakeLists.txt"),
            "cmake_minimum_required(VERSION 3.31)\nproject(Edited NONE)\n",
        )
        .unwrap();
    assert!(workspace.runtime().is_none());
}
