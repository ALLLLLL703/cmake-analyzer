/// Validate the server's selected position unit and store it for later handler contexts.
/// No I/O; leaves the previous session encoding untouched on failure.
///
/// # Arguments
/// - `context` `[in,out]`: session whose encoding atomic is overwritten only after validation.
/// - `result` `[in]`: initialize reply; absent `position_encoding` selects UTF-16.
/// # Returns
/// `Ok(())` after storing UTF-8 (0), UTF-16 (1) or UTF-32 (2); `Err(error)` if the
/// selection was not offered or is unsupported by this wrapper.
/// # Errors
/// InternalError (-32603) for an unoffered encoding or an offered encoding other
/// than UTF-8, UTF-16 or UTF-32. No encoding is stored on either error path.
/// # Algorithm
/// Default an omitted selection to UTF-16, check the cached offer list, then map
/// the selected spelling to the session's numeric unit and publish it atomically.
/// # Flow
/// ```text
/// [reply selection or UTF-16]
///              |
///          <offered?>
///          /       \\
///        no        yes
///         |         |
///      [error] <known unit?>
///               /       \\
///             no        yes
///              |         |
///           [error] [store encoding]
///                        |
///                        v
///                    [Ok(())]
/// ```
/// # Examples
/// ```text
/// initialized_result(&context, &result).await?;
/// let unit = context.client.session.encoding.load(Ordering::Acquire);
/// assert!(unit <= 2);
/// ```
pub(super) async fn initialized_result(
    context: &Context,
    result: &InitializeResult,
) -> ServerResult<()> {
    let encoding = result
        .capabilities
        .position_encoding
        .as_ref()
        .map_or("utf-16", |v| v.0.as_ref());
    if !context
        .client
        .session
        .offered_encodings
        .lock()
        .await
        .iter()
        .any(|v| v == encoding)
    {
        return Err(ServerError::new(
            -32603,
            "Server chose an unoffered position encoding",
        ));
    }
    let value = match encoding {
        "utf-8" => 0,
        "utf-16" => 1,
        "utf-32" => 2,
        _ => return Err(ServerError::new(-32603, "Unsupported position encoding")),
    };
    context
        .client
        .session
        .encoding
        .store(value, Ordering::Release);
    Ok(())
}
